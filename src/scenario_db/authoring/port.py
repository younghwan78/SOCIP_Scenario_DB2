"""R-8: port an approved scenario source into an ejected root project (the in-house E2700 path).

A private E2700 project cannot ``extends`` the public E2600 project (tree.py: a parent must share the platform or
be extended by it directly), so the structure moves by copy:

1. the source scenario directory ``projects/<from>/scenarios/<uc>/`` (scenario, variants, knobs, sizes,
   sw_timing, measured slots: every ``*.yaml``) is copied to ``projects/<to>/scenarios/<new id>/``;
2. ids are renamed with the target's eject record (``ejected-from.yaml`` ``id_map``, whose ``parent_project`` must
   be ``<from>``), plus ``<uc> -> <new id>`` (``id_map[uc]`` and an optional suffix). The text is rewritten token by
   token so comments survive; the parsed result must equal ``rename_value`` of the source, else the file is dumped;
3. ``ported-from.yaml`` records the source project / scenario / commit and the source file hashes;
4. the target project is compiled and validated: ids, modes or fields the target catalog lacks come back as
   problems (nothing is written to a fixture).

``port_status`` compares the record with the source today (changed / added / removed files) to decide a re-port.
Values (solution tables, KPI targets, measured slots) are filled in the ported copy only.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import re
import shutil
from pathlib import Path
from typing import Any

from scenario_db.authoring import yamlio
from scenario_db.authoring.errors import AuthoringError
from scenario_db.authoring.rename import rename_value

RECORD = "ported-from.yaml"
EJECT_RECORD = "ejected-from.yaml"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _id_map(root: Path, src: str, dst: str) -> dict[str, str]:
    record = root / "projects" / dst / EJECT_RECORD
    if not record.exists():
        raise AuthoringError(f"project '{dst}' has no {EJECT_RECORD}: port needs the eject id map")
    doc = yamlio.load(record) or {}
    if doc.get("parent_project") != src:
        raise AuthoringError(f"project '{dst}' was ejected from '{doc.get('parent_project')}', not '{src}'")
    return dict(doc.get("id_map") or {})


def _rename_text(text: str, id_map: dict[str, str]) -> str:
    """Exact-token id replacement (an id is never part of a longer id: no word / '-' / '.' around it)."""
    if not id_map:
        return text
    pattern = re.compile(r"(?<![\w.-])(" + "|".join(re.escape(k) for k in sorted(id_map, key=len, reverse=True))
                         + r")(?![\w-])")
    return pattern.sub(lambda m: id_map[m.group(1)], text)


def _source_files(sdir: Path) -> list[Path]:
    return sorted(p for p in sdir.iterdir() if p.is_file() and p.suffix in (".yaml", ".yml") and p.name != RECORD)


def port_scenario(root: Path, uc: str, *, src: str, dst: str, suffix: str = "", commit: str | None = None,
                  replace: bool = False, smoke: bool = True) -> dict[str, Any]:
    """Copy ``uc`` of project ``src`` into the ejected root project ``dst``; returns the port report."""
    sdir = root / "projects" / src / "scenarios" / uc
    if not (sdir / "scenario.yaml").exists():
        raise AuthoringError(f"project '{src}' has no scenario source '{uc}' (scenarios/{uc}/scenario.yaml)")
    spec = yamlio.load(root / "projects" / dst / "project.yaml") or {}
    if spec.get("extends"):
        raise AuthoringError(f"project '{dst}' extends '{spec['extends']}': port into an ejected root project")
    id_map = _id_map(root, src, dst)
    new_id = id_map.get(uc, uc) + suffix
    id_map = {**id_map, uc: new_id}
    ddir = root / "projects" / dst / "scenarios" / new_id
    if ddir.exists():
        if not replace:
            raise AuthoringError(f"scenarios/{new_id} already exists in '{dst}' (pass replace to re-port)")
        shutil.rmtree(ddir)
    ddir.mkdir(parents=True)
    files: dict[str, str] = {}
    dumped: list[str] = []
    for path in _source_files(sdir):
        text = path.read_text(encoding="utf-8")
        files[path.name] = _sha(path)
        want = rename_value(yamlio.load(path), id_map)
        out = _rename_text(text, id_map)
        target = ddir / path.name
        target.write_text(out, encoding="utf-8", newline="\n")
        if yamlio.load(target) != want:     # a token the text rule cannot see: fall back to the parsed rename
            yamlio.dump(target, want)
            dumped.append(path.name)
    yamlio.dump(ddir / RECORD, {
        "kind": "authoring.port_record", "source_project": src, "source_scenario": uc, "scenario": new_id,
        "commit": commit, "date": _dt.date.today().isoformat(), "files": files,
    }, header="GENERATED by `authoring port-scenario`: the source this scenario was copied from.\n"
               "Used by `authoring port-status` to see source changes since the port. Do not edit.")
    out = {"scenario": new_id, "files": sorted(files), "rewritten_by_dump": dumped,
           "problems": port_problems(root, dst, new_id)}
    if smoke and not out["problems"]:
        out["smoke"] = port_smoke(root, dst, new_id)
    return out


def port_smoke(root: Path, dst: str, scenario: str) -> dict[str, Any]:
    """Run the Timing Budget once per variant of the ported scenario on the target project's compiled documents
    (no database, the first ``00_hw/dvfs-*`` table): what the target catalog still lacks shows up as an error
    message with the variants it stops. Returns ``{variants, ok, errors: {message: [variant ids]}}``."""
    from scenario_db.authoring.tree import compile_project
    from scenario_db.db.models.capability import IpCatalog
    from scenario_db.db.models.definition import ScenarioVariant
    from scenario_db.db.repositories.scenario_graph import CanonicalScenarioGraph
    from scenario_db.db.repositories.variant_resolution import resolve_variant_from_rows
    from scenario_db.db.models.definition import Scenario
    from scenario_db.sim.models import DVFSTable
    from scenario_db.sim.timing_budget import TimingBudgetOptions, analyze_timing_budget

    docs = {d.rel: d.data for d in compile_project(root, dst)["documents"]}
    doc = docs.get(f"02_definition/{scenario}.yaml")
    if doc is None:
        raise AuthoringError(f"project '{dst}' compiles no scenario {scenario}")
    ip_catalog = {d["id"]: IpCatalog(id=d["id"], schema_version=str(d["schema_version"]), category=d.get("category"),
                                     hierarchy=d.get("hierarchy") or {}, capabilities=d.get("capabilities") or {},
                                     yaml_sha256="port-smoke")
                  for rel, d in sorted(docs.items()) if rel.startswith("00_hw/ip-")}
    dvfs = next((d for rel, d in sorted(docs.items()) if rel.startswith("00_hw/dvfs-")), None)
    tables = {k: DVFSTable.model_validate(v) for k, v in ((dvfs or {}).get("domains") or {}).items()}
    fields = set(ScenarioVariant.__table__.columns.keys())
    scen = Scenario(id=doc["id"], schema_version=str(doc.get("schema_version") or "2.2"), project_ref=doc["project_ref"],
                    metadata_=doc.get("metadata") or {}, pipeline=doc.get("pipeline") or {},
                    size_profile=doc.get("size_profile"), design_axes=doc.get("design_axes"),
                    power_options=doc.get("power_options"), yaml_sha256="port-smoke")
    rows = {v["id"]: ScenarioVariant(scenario_id=scen.id, **{k: x for k, x in v.items() if k in fields})
            for v in doc.get("variants") or []}
    errors: dict[str, list[str]] = {}
    for vid in rows:
        try:
            graph = CanonicalScenarioGraph(scenario=scen, variant=resolve_variant_from_rows(rows, scen.id, vid),
                                           ip_catalog=ip_catalog)
            report = analyze_timing_budget(graph, TimingBudgetOptions(throughput_model="pipelined"),
                                           dvfs_tables=tables)
            if report.get("jobs_error"):
                errors.setdefault(f"jobs: {report['jobs_error']}", []).append(vid)
        except Exception as exc:  # noqa: BLE001 - every failure is a finding of the port
            errors.setdefault(f"{type(exc).__name__}: {exc}", []).append(vid)
    failed = {v for vs in errors.values() for v in vs}
    return {"variants": len(rows), "ok": len(rows) - len(failed), "errors": errors}


def port_problems(root: Path, dst: str, scenario: str) -> list[str]:
    """Compile + validate the target project; the problems of the ported scenario (and compile errors)."""
    from scenario_db.authoring.tree import compile_project
    from scenario_db.authoring.validate import validate_documents

    try:
        report = compile_project(root, dst)
    except AuthoringError as exc:
        return [f"compile: {exc}"]
    validation = validate_documents(report["documents"])
    return [e for e in validation["errors"] if scenario in e]


def port_status(root: Path, dst: str, scenario: str) -> dict[str, Any]:
    """Source changes since the port: files changed / added / removed (by hash)."""
    record = root / "projects" / dst / "scenarios" / scenario / RECORD
    if not record.exists():
        raise AuthoringError(f"scenarios/{scenario} of '{dst}' has no {RECORD}")
    doc = yamlio.load(record) or {}
    sdir = root / "projects" / str(doc["source_project"]) / "scenarios" / str(doc["source_scenario"])
    now = {p.name: _sha(p) for p in _source_files(sdir)} if sdir.exists() else {}
    then = dict(doc.get("files") or {})
    return {"source": f"{doc['source_project']}/{doc['source_scenario']}", "commit": doc.get("commit"),
            "changed": sorted(k for k in then.keys() & now.keys() if then[k] != now[k]),
            "added": sorted(now.keys() - then.keys()), "removed": sorted(then.keys() - now.keys()),
            "source_missing": not sdir.exists()}
